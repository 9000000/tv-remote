ROOT = pathlib.Path(__file__).resolve().parent.parent

sprite = '<svg xmlns="http://www.w3.org/2000/svg" style="display:none">' + "".join(
    f'<symbol id="i-{n}" viewBox="0 0 24 24">' + "".join(f'<path d="{d}"/>' for d in paths) + "</symbol>" for n, paths in ICONS.items()) + "</svg>"
for page in (ROOT / "app/web/static/index.html", ROOT / "app/tv/assets/index.html"):
    if page.exists():
        s = page.read_text()
        s2 = re.sub(r"<!-- icons:start -->.*?<!-- icons:end -->", "<!-- icons:start -->" + sprite + "<!-- icons:end -->", s, flags=re.S)
        assert s2 != s or sprite in s, f"{page} has no <!-- icons:start --><!-- icons:end --> marker"
        page.write_text(s2)

for app in ("android", "tv"):
    out = ROOT / "app" / app / "res/drawable"
    for n, paths in ICONS.items():
        body = "".join(f'\n    <path android:pathData="{d}" android:strokeColor="#FFFFFFFF" android:strokeWidth="2" android:strokeLineCap="round" android:strokeLineJoin="round" />' for d in paths)
